def add_to_font(text):
    """Voegt de letters toe vóór de afsluitende } van de font-dict; behoudt de regeleinden van het bestand."""
    nl = "\r\n" if "\r\n" in text else "\n"
    entries = []
    for ch, rows in GLYPHS.items():
        if '"%s":' % ch in text:
            continue
        width = len(rows[0])
        bits = [("    0b" + r.replace("#", "1").replace(".", "0") + ",") for r in rows]
        entries.append(nl.join(['  "%s": [' % ch, "    %d," % width] + bits + ["  ],"]))
    if not entries:
        return text
    end = text.rstrip().rfind("}")
    return text[:end] + nl + "  ### GEORGISCH (Mkhedruli)" + nl + nl + (nl + nl).join(entries) + nl + nl + text[end:]


